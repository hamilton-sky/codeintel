# --------------------------------------------------------------------------- pure helpers

def _ident(part: str) -> str:
    """Map every non-alnum character to `_` — LikeC4 identifiers are `[A-Za-z_][A-Za-z0-9_]*` —
    and escape a bare reserved word with a trailing `_` (defect (c)): `src/model.ts` would
    otherwise render `model = module 'model' { … }` *inside* `model { }`, which LikeC4 1.59.2
    cannot parse. The escape only touches the IDENTIFIER; the element's `title`/`path` metadata
    is built from the unsanitised path elsewhere and is never passed through this function, so the
    rendered display name is unaffected."""
    out = "".join(c if (c.isalnum() or c == "_") else "_" for c in part)
    if not out:
        out = "x"
    if out[0].isdigit():
        out = "n" + out
    if out.lower() in _RESERVED_WORDS:
        out = out + "_"
    return out


def _match_ext(path: str) -> str:
    for ext in SRC_EXT:
        if path.endswith(ext):
            return ext
    return ""


def _strip_ext(name: str) -> str:
    for ext in SRC_EXT:
        if name.endswith(ext):
            return name[: -len(ext)]
    return name


def _drop_reason(path: str, *, include_tests: bool) -> str:
    """Why `keep_source` would drop *path* — `""` when it is kept. Shared with `build_c4_payload`
    so the noise/test/kept counts in `stats` cannot drift from the filter that actually ran."""
    p = path.replace("\\", "/")
    if p.endswith(EXCLUDE_EXT) or not p.endswith(SRC_EXT):
        return "nonsource"
    segments = p.split("/")
    if any(seg in NOISE_DIRS for seg in segments):
        return "noise"
    if not include_tests and any(seg in TEST_DIRS for seg in segments):
        return "test"
    return ""


def keep_source(paths: list[str], *, include_tests: bool = False, scope: tuple = ()) -> list[str]:
    """Drop noise dirs (any segment position), test dirs (unless *include_tests*), non-source and
    generated-declaration extensions, then apply *scope* as an additional prefix filter. Pure."""
    scope = tuple(str(s).strip("/") for s in (scope or ()) if s)
    out: list[str] = []
    for path in paths:
        p = str(path or "")
        if not p or _drop_reason(p, include_tests=include_tests):
            continue
        if scope and not any(p == s or p.startswith(s + "/") for s in scope):
            continue
        out.append(p)
    return out


def element_key(path: str, depth: int) -> str:
    """The file-path -> element-id rule that makes files and directories the same code path.

    `len(segments) <= depth` -> the element IS the file (extension stripped); otherwise the
    element is the directory `segments[:depth]`. A file at or below its own path length always
    collapses to itself, which is what lets a shorter file (`main.py`) and a deeper directory
    that shares its stem (`main/sub/`) land at the same key when they should shadow-merge."""
    segments = str(path or "").split("/")
    if len(segments) <= depth:
        segments = list(segments)
        segments[-1] = _strip_ext(segments[-1])
        return ".".join(segments)
    return ".".join(segments[:depth])


def _rendered_element_count(paths: list[str], depth: int) -> int:
    """How many `model {}` nodes *paths* actually render at *depth* — not just the file/directory
    GROUPS `element_key` produces, but every bare containment `area` `_emit_tree` synthesises
    above them too (defect (h)). Two elements that share a dotted prefix neither of them IS (e.g.
    `a.b.leaf` and `a.c.leaf`, with no element literally named `a`) still cost a rendered `a = area
    { … }` wrapper — `fit_depth`'s cap search must count it, or it can auto-fit a depth whose
    *real* element count already exceeds `VIEW_ELEMENT_CAP`. Pure."""
    keys = {element_key(p, depth) for p in paths}
    rendered: set[str] = set()
    for key in keys:
        parts = key.split(".")
        for i in range(1, len(parts) + 1):
            rendered.add(".".join(parts[:i]))
    return len(rendered)


def fit_depth(paths: list[str], *, cap: int = VIEW_ELEMENT_CAP, requested: int | None = None) -> dict:
    """The deepest depth whose element count still fits *cap* — or the depth the caller forced.

    `table` always carries every depth actually probed (1..min(MAX_DEPTH, longest path)); the
    search stops early once depth reaches the longest kept path, because every deeper depth would
    produce the identical element set (file granularity). Pure."""
    max_len = max((len(p.split("/")) for p in paths), default=1)
    ceiling = min(MAX_DEPTH, max(max_len, 1))
    table: dict[int, int] = {}
    for d in range(1, ceiling + 1):
        table[d] = _rendered_element_count(paths, d)
        if d >= max_len:
            break

    if requested is not None:
        depth = max(1, int(requested))
        if depth not in table:
            table[depth] = _rendered_element_count(paths, depth)
        return {"depth": depth, "how": "requested", "table": table,
                "over_cap": table[depth] > cap, "cap": cap}

    fitting = [d for d, n in table.items() if n <= cap]
    if fitting:
        return {"depth": max(fitting), "how": "auto-fit", "table": table,
                "over_cap": False, "cap": cap}
    # Even the coarsest cut (d1) exceeds the cap: emit it anyway rather than refuse. A model that
    # is over the view cap is still more useful than no model at all.
    return {"depth": 1, "how": "auto-fit", "table": table, "over_cap": True, "cap": cap}


def _resolve_element_ids(groups: dict[str, dict]) -> tuple[dict[str, str], int, dict[str, str]]:
    """Sanitise every raw dotted key in *groups* into a LikeC4 identifier, resolving a
    sanitisation collision by suffixing only the COLLIDING SEGMENT (defect (e)).

    The old rule appended `__2` to the whole dotted id, so `my-app/core/a.ts` and
    `my_app/core/b.ts` (both sanitising to `my_app.core`) became `my_app.core` and
    `my_app.core__2` — falsely claiming both live under one shared `my_app` area, with nothing in
    the tree representing `my-app` at all. Walking a trie built from the RAW (pre-sanitisation)
    segments instead means a collision at one path position only disturbs the identifier at that
    position — `my_app.core` and `my_app__2.core` — so an ancestor that never collided keeps its
    real name.

    Returns ``(raw_key -> element_id, id_collisions, id_path -> real_segment_name)``. The third
    dict covers every node in the trie, leaf or bare intermediate, keyed by the RESOLVED dotted id
    up to that point — it is what lets a synthetic containment `area` (one with no `groups` entry
    of its own) still show its real, unsanitised directory name (defect (i)). Pure."""
    root: dict = {"children": {}, "terminal": None, "min_path": ""}
    for raw_key in groups:
        node = root
        for seg in raw_key.split("."):
            node = node["children"].setdefault(seg, {"children": {}, "terminal": None, "min_path": ""})
        node["terminal"] = raw_key

    def _fill_min_path(node: dict) -> str:
        candidates = [min(groups[node["terminal"]]["paths"])] if node["terminal"] is not None else []
        candidates.extend(_fill_min_path(child) for child in node["children"].values())
        node["min_path"] = min(candidates)
        return node["min_path"]

    if root["children"]:
        _fill_min_path(root)

    resolved: dict[str, str] = {}
    segment_titles: dict[str, str] = {}
    id_collisions = 0

    def _walk(node: dict, prefix: tuple[str, ...]) -> None:
        nonlocal id_collisions
        if node["terminal"] is not None:
            resolved[node["terminal"]] = ".".join(prefix)
        sid_groups: dict[str, list[str]] = {}
        for raw_seg in node["children"]:
            sid_groups.setdefault(_ident(raw_seg), []).append(raw_seg)
        for sid, raw_segs in sid_groups.items():
            if len(raw_segs) == 1:
                raw_seg = raw_segs[0]
                seg_ids = [sid]
            else:
                id_collisions += 1
                raw_segs = sorted(raw_segs, key=lambda s: node["children"][s]["min_path"])
                seg_ids = [sid if i == 0 else f"{sid}__{i + 1}" for i in range(len(raw_segs))]
            for raw_seg, seg_id in zip(raw_segs, seg_ids, strict=True):
                full_id = ".".join((*prefix, seg_id))
                segment_titles[full_id] = raw_seg
                _walk(node["children"][raw_seg], (*prefix, seg_id))

    _walk(root, ())
    return resolved, id_collisions, segment_titles


def group_elements(paths: list[str], depth: int) -> dict:
    """Group *paths* into elements at *depth*, merging file/directory shadows and resolving
    sanitisation collisions with a `__2`/`__3` suffix on the colliding segment (design section
    3.2; defect (e)). Pure.

    Returns ``{"groups": {element_id: {"paths": [...], "dir_prefix": str|None}}, "element_of":
    {path: element_id}, "shadowed_files": int, "id_collisions": int, "segment_titles": {id_path:
    real_name}}``. `element_of` is keyed by the FINAL sanitised element id, ready for edge
    aggregation to key off directly."""
    groups: dict[str, dict] = {}   # raw key -> {"paths": [...], "dir_prefix": str|None}
    for pth in paths:
        segs = pth.split("/")
        key = element_key(pth, depth)
        g = groups.setdefault(key, {"paths": [], "dir_prefix": None})
        g["paths"].append(pth)
        if len(segs) > depth:
            g["dir_prefix"] = "/".join(segs[:depth])

    shadowed_files = 0
    for g in groups.values():
        if g["dir_prefix"] is not None:
            shadowed_files += sum(1 for pth in g["paths"] if len(pth.split("/")) <= depth)

    key_to_id, id_collisions, segment_titles = _resolve_element_ids(groups)

    element_of: dict[str, str] = {}
    for key, g in groups.items():
        eid = key_to_id[key]
        for pth in g["paths"]:
            element_of[pth] = eid

    return {
        "groups": {key_to_id[key]: g for key, g in groups.items()},
        "element_of": element_of,
        "shadowed_files": shadowed_files,
        "id_collisions": id_collisions,
        "segment_titles": segment_titles,
    }


def _top_extensions(paths: list[str], n: int = 8) -> list[list]:
    counts: dict[str, int] = {}
    for p in paths:
        ext = os.path.splitext(p)[1] or "(none)"
        counts[ext] = counts.get(ext, 0) + 1
    return [[ext, count] for ext, count in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:n]]


def _count_value(row: dict) -> int:
    """The `count(*)` aggregate off an import row. The real codebase-memory-mcp backend echoes
    the column back as `COUNT(*)` (uppercase) although the design's row-shape example (and the
    fixtures in tests/test_c4.py, which follow it) spell it lowercase — observed by running this
    module against six real indexed repos, where every relation weight silently read as 0 until
    this handled both. Checked case-insensitively so neither spelling is a coincidence this
    depends on."""
    for key, value in row.items():
        if str(key).replace(" ", "").lower() == "count(*)":
            try:
                return int(value or 0)
            except (TypeError, ValueError):
                return 0
    return 0


def _tech_for(paths: list[str]) -> str:
    counts: dict[str, int] = {}
    for p in paths:
        tech = _TECH.get(_match_ext(p), "Source")
        counts[tech] = counts.get(tech, 0) + 1
    top2 = sorted(counts.items(), key=lambda kv: -kv[1])[:2]
    return ", ".join(t for t, _n in top2)


HOTSPOT_PERCENTILE = 90        # top decile of the ranked population, nearest-rank
MIN_HOTSPOT_FAN_IN = 3         # floor so a small/uniform repo does not get a fifth of it painted red


def _hotspot_threshold(fan_in_values: list[int]) -> int | None:
    """The fan-in an element needs to be flagged `#hotspot` — the `HOTSPOT_PERCENTILE`th of
    *fan_in_values*, floored at `MIN_HOTSPOT_FAN_IN` so a repo whose busiest element still only has
    one or two incoming edges is not misleadingly declared to have a hotspot. `None` when
    *fan_in_values* is empty: there is no population to rank, so nothing is flagged (defect (g)).

    A FIXED `>= 5` cutoff tagged 13 of 60 elements on this repo — over a fifth of the diagram red,
    regardless of how the other 59 were actually distributed. Ranking against the population's own
    spread keeps the signal meaningful across repos of very different densities. Pure."""
    if not fan_in_values:
        return None
    values = sorted(fan_in_values)
    idx = min(len(values) - 1, (len(values) * HOTSPOT_PERCENTILE) // 100)
    return max(values[idx], MIN_HOTSPOT_FAN_IN)


# --------------------------------------------------------------------------- index_repo

# Reasons that mean "there is no graph index for this repo YET" — the one class of failure a
# caller can fix on the user's behalf rather than printing an instruction and exiting 1.
# `no-source-files` is deliberately NOT here: the index exists and was read, it simply holds no
# source, so re-indexing would spend minutes to produce the identical empty model.
INDEXABLE_REASONS: tuple[str, ...] = ("project-not-indexed", "project-not-indexed-standalone")
INDEX_TIMEOUT_MS = 300_000    # same ceiling Reindexer._graph_reindex allows a cold index


def index_repo(project_root: Any, *, timeout_ms: int = INDEX_TIMEOUT_MS) -> dict:
    """Build (or refresh) the GRAPH index for *project_root*, so a model can be built from a repo
    that has never been indexed. Returns ``{"ok": bool, "problem": str}``; never raises.

    Graph-only on purpose. A `.c4` model is derived entirely from `File` nodes and
    `IMPORTS`/`CALLS`/`USAGE` edges, so the semantic half of `codeintel index` — embedding every
    chunk, measured at 2m35s for a 58-file repo against 6s for the graph half — buys this command
    nothing. Indexing only what the model reads is the difference between an auto-index a user
    will tolerate inline and one they will kill.

    Routes through the same `index_repository` seam as `Reindexer._graph_reindex`, including its
    `repo_path` argument name: the backend answers the wrong name (`project_root`) with "Indexing
    worker crashed on a file", which reads like a parser bug in some source file and has already
    sent one fix looking in the wrong place.
    """
    try:
        from codeintel.providers.graph import GraphProvider

        p = GraphProvider()
        if not getattr(p, "available", False):
            return {"ok": False, "problem": "the graph engine is unavailable"}
        result = p._run("index_repository", {"repo_path": str(project_root or "")}, timeout_ms)
        # A backend-reported error is surfaced, not swallowed — swallowing it is what let a broken
        # reindex look exactly like a working one (see Reindexer._graph_reindex).
        if result is None:
            return {"ok": False, "problem": "the graph backend returned nothing "
                                            "(it timed out, crashed, or rejected the call)"}
        if isinstance(result, dict) and str(result.get("status")) == "error":
            detail = result.get("hint") or result.get("message") or result
            return {"ok": False, "problem": str(detail)}
        return {"ok": True, "problem": ""}
    except Exception as exc:
        log_swallowed("c4.index_repo", exc)
        return {"ok": False, "problem": str(exc)}


# --------------------------------------------------------------------------- build_c4_payload

def build_c4_payload(project_root: Any, *, depth: int | None = None, scope: tuple = (),
                     include_tests: bool = False, timeout_ms: int = 8000) -> dict:
    """Query the graph engine for a project's File/IMPORTS slice, roll it up into a LikeC4-shaped
    payload at an auto-fit (or requested) directory depth. Never raises -- returns a flat `reason`
    string and empty lists on any failure."""
    try:
        from codeintel.providers.graph import GraphProvider, _repo_display_name

        p = GraphProvider()
        if not getattr(p, "available", False):
            return {**_EMPTY, "reason": "engine-unavailable"}
        resolution = p._resolve_project(str(project_root or ""))
        if resolution is None:
            return {**_EMPTY, "reason": "project-not-indexed"}
        # A generated model is a whole-repo artifact rooted at this project's own name — an
        # ancestor match would model the containing monorepo under this repo's label. Refuse, like
        # `grapher.build_graph_payload` does for the HTML viewer.
        if resolution.is_ancestor:
            return {**_EMPTY, "reason": "project-not-indexed-standalone"}
        project = resolution.name
        display_name = _repo_display_name(str(project_root or "")) or project

        file_rows = p._query_rows(
            f"MATCH (f:File) RETURN f.file_path LIMIT {MAX_FILE_ROWS}", project, timeout_ms) or []
        files_truncated = len(file_rows) >= MAX_FILE_ROWS
        all_paths = [str(r.get("f.file_path") or "") for r in file_rows]
        all_paths = [fp for fp in all_paths if fp]
        files_seen = len(all_paths)

        # churn is decoration, not structure (defect 6.10): its own query, degrading to 0 on any
        # failure rather than losing the whole model for a metric.
        churn_map: dict[str, int] = {}
        try:
            churn_rows = p._query_rows(
                f"MATCH (f:File) RETURN f.file_path, f.change_count LIMIT {MAX_FILE_ROWS}",
                project, timeout_ms) or []
            for r in churn_rows:
                fp = str(r.get("f.file_path") or "")
                if fp:
                    churn_map[fp] = int(r.get("f.change_count") or 0)
        except Exception as exc:
            log_swallowed("c4.build_c4_payload.churn", exc)
            churn_map = {}

        files_noise = sum(1 for pth in all_paths
                          if _drop_reason(pth, include_tests=include_tests) == "noise")
        files_test = sum(1 for pth in all_paths
                         if _drop_reason(pth, include_tests=include_tests) == "test")
        kept_all = keep_source(all_paths, include_tests=include_tests)

        scope_tuple = tuple(str(s).strip("/") for s in (scope or ()) if s)
        if scope_tuple:
            kept = keep_source(all_paths, include_tests=include_tests, scope=scope_tuple)
            if not kept:
                dirs = sorted({pth.split("/", 1)[0] for pth in kept_all})
                return {**_EMPTY, "project": display_name,
                        "stats": {**_EMPTY_STATS, "files_seen": files_seen,
                                  "files_noise": files_noise, "files_test": files_test,
                                  "scope_available_dirs": dirs},
                        "reason": "scope-not-found"}
        else:
            kept = kept_all

        if not kept:
            return {**_EMPTY, "project": display_name,
                    "stats": {**_EMPTY_STATS, "files_seen": files_seen,
                              "top_extensions": _top_extensions(all_paths)},
                    "reason": "no-source-files"}

        fit = fit_depth(kept, cap=VIEW_ELEMENT_CAP, requested=depth)
        chosen = fit["depth"]

        # --- group kept files into elements at `chosen` depth --------------------------------
        grouped = group_elements(kept, chosen)
        groups, element_of = grouped["groups"], grouped["element_of"]
        shadowed_files, id_collisions = grouped["shadowed_files"], grouped["id_collisions"]
        segment_titles = grouped["segment_titles"]

        # --- edges: hop 1 (File->Symbol collapsed to File->File by q3's count(*)) already done
        # by the backend; hop 2 rolls File->File up to Element->Element, summing weights.
        #
        # IMPORTS alone is a low-recall edge source (module-level static imports only — lazy and
        # function-body imports are invisible to it) and was measured fabricating edges from source
        # files to test files that do not reference them. CALLS|USAGE — already this codebase's
        # higher-recall relation for fan-in (mapper.py's `_FAN_IN_CYPHER`) and the call graph
        # (grapher.py) — is unioned in here for the same reason: it reproduces nearly everything
        # IMPORTS finds and recovers real cross-module edges IMPORTS misses entirely (measured:
        # gateway -> providers.*, most of commands/* -> its collaborators). It is not a strictly
        # cleaner source — it carries its own bare-name-collision noise — so every relation records
        # WHICH source(s) it came from (`rel_sources`) rather than asserting it is an import.
        import_rows = p._query_rows(
            f"MATCH (a:File)-[r:IMPORTS]->(b) RETURN a.file_path, b.file_path, count(*) "
            f"LIMIT {MAX_IMPORT_ROWS}", project, timeout_ms) or []
        imports_truncated = len(import_rows) >= MAX_IMPORT_ROWS

        calls_rows = p._query_rows(
            f"MATCH (a)-[c:CALLS|USAGE]->(b) RETURN a.file_path, b.file_path, count(*) "
            f"LIMIT {MAX_CALLS_ROWS}", project, timeout_ms) or []
        calls_truncated = len(calls_rows) >= MAX_CALLS_ROWS

        rel_weights: dict[tuple, int] = {}
        rel_sources: dict[tuple, set] = {}
        dropped: list[dict] = []
        internal_by_elem: dict[str, int] = {}
        edges_internal = 0
        edges_dropped_ancestor = 0
        edges_dropped_out_of_scope = 0

        # `a`/`b` on the CALLS|USAGE query are not `:File`-typed (the edge originates on whatever
        # symbol node carries it), so their file_path can point at a builtin/synthetic node (empty,
        # or `<...>`) or a non-source file. No separate synthetic-node filter is needed for that —
        # unlike grapher.py's standalone `_synth` check — because every endpoint here is looked up
        # against `element_of`, which `keep_source` already built from real, kept `File` nodes only;
        # a synthetic or non-source path can never be a member of it and is dropped as out-of-scope
        # below, same as any other out-of-scope endpoint.
        for rows, source in ((import_rows, "imports"), (calls_rows, "calls_usage")):
            for row in rows:
                a_fp = str(row.get("a.file_path") or "")
                b_fp = str(row.get("b.file_path") or "")
                n = _count_value(row)
                if a_fp not in element_of or b_fp not in element_of:
                    edges_dropped_out_of_scope += 1
                    if len(dropped) < DROPPED_REPORT_CAP:
                        dropped.append({"from": a_fp, "to": b_fp, "why": "out-of-scope"})
                    continue
                eid_a, eid_b = element_of[a_fp], element_of[b_fp]
                if eid_a == eid_b:
                    edges_internal += n
                    internal_by_elem[eid_a] = internal_by_elem.get(eid_a, 0) + n
                    continue
                if eid_a.startswith(eid_b + ".") or eid_b.startswith(eid_a + "."):
                    edges_dropped_ancestor += 1
                    if len(dropped) < DROPPED_REPORT_CAP:
                        dropped.append({"from": eid_a, "to": eid_b, "why": "ancestor"})
                    continue
                pair = (eid_a, eid_b)
                rel_weights[pair] = rel_weights.get(pair, 0) + n
                rel_sources.setdefault(pair, set()).add(source)

        # `imports` when an IMPORTS edge contributed at all (literally true even if CALLS|USAGE also
        # confirmed it); `calls_usage` only when IMPORTS never saw this pair — never the reverse, so
        # the kind never claims stronger evidence than what was actually found.
        relations = [
            {"from": a, "to": b, "n": n,
             "kind": "imports" if "imports" in rel_sources[(a, b)] else "calls_usage"}
            for (a, b), n in rel_weights.items()
        ]
        edges_from_imports_only = sum(1 for s in rel_sources.values() if s == {"imports"})
        edges_from_calls_usage_only = sum(1 for s in rel_sources.values() if s == {"calls_usage"})
        edges_from_both = sum(1 for s in rel_sources.values() if len(s) == 2)

        fan_in: dict[str, int] = {}
        fan_out: dict[str, int] = {}
        # Ranked separately from `fan_in` (defect (g)): CALLS|USAGE matches by bare symbol name, so
        # e.g. every `dict.get(...)` call in the repo lands on `cache.py`'s `ContentHashCache.get`
        # — measured live at 54 of 60 rows on this repo's own `cache.py`. Only an `imports`-labelled
        # relation (a real, file-scoped IMPORTS edge — see the `kind` rule above) is trustworthy
        # enough to RANK elements against each other for a "this is a hotspot" visual claim; the
        # union-based `fan_in` above stays as descriptive metadata only, same as before.
        import_fan_in: dict[str, int] = {}
        for r in relations:
            fan_in[r["to"]] = fan_in.get(r["to"], 0) + 1
            fan_out[r["from"]] = fan_out.get(r["from"], 0) + 1
            if r["kind"] == "imports":
                import_fan_in[r["to"]] = import_fan_in.get(r["to"], 0) + 1

        hotspot_threshold = _hotspot_threshold(list(import_fan_in.values()))

        elements: list[dict] = []
        cross_language_merges = 0
        for eid, g in groups.items():
            paths = g["paths"]
            is_dir = g["dir_prefix"] is not None
            is_cross_language = not is_dir and len(paths) > 1
            if is_dir:
                path_str = g["dir_prefix"] + "/"
                title = g["dir_prefix"].rsplit("/", 1)[-1]
                kind = "area"
                tech = _tech_for(paths)
            elif is_cross_language:
                # `element_key` strips the extension, so two files that share a directory and a
                # basename but differ only in language (`api/index.ts` + `api/index.js`) collapse
                # into one group (defect (d)). Kept merged — undoing it would need a second element
                # identity axis this design does not otherwise have — but reported honestly rather
                # than silently: every path is named in `metadata.path`, not just the first, `tech`
                # reflects every language actually present, and `stats.cross_language_merges` (plus
                # the DSL header) says how many elements this happened to.
                cross_language_merges += 1
                path_str = ", ".join(sorted(paths))
                title = _strip_ext(paths[0].rsplit("/", 1)[-1])
                kind = "module"
                tech = _tech_for(paths)
            else:
                path_str = paths[0]
                title = _strip_ext(paths[0].rsplit("/", 1)[-1])
                kind = "module"
                tech = _TECH.get(_match_ext(paths[0]), "Source")
            elements.append({
                "id": eid, "path": path_str, "title": title, "kind": kind, "tech": tech,
                "files": len(paths), "churn": sum(churn_map.get(pth, 0) for pth in paths),
                "fan_in": fan_in.get(eid, 0), "fan_out": fan_out.get(eid, 0),
                "internal_imports": internal_by_elem.get(eid, 0),
                "import_fan_in": import_fan_in.get(eid, 0),
                "hotspot": bool(hotspot_threshold is not None
                               and import_fan_in.get(eid, 0) >= hotspot_threshold),
            })

        hotspot_count = sum(1 for e in elements if e["hotspot"])

        stats = {
            "files_seen": files_seen, "files_noise": files_noise, "files_test": files_test,
            "files_kept": len(kept), "imports_seen": len(import_rows),
            "calls_usage_seen": len(calls_rows),
            "edges_kept": len(relations), "edges_internal": edges_internal,
            "edges_dropped_ancestor": edges_dropped_ancestor,
            "edges_dropped_out_of_scope": edges_dropped_out_of_scope,
            "edges_from_imports_only": edges_from_imports_only,
            "edges_from_calls_usage_only": edges_from_calls_usage_only,
            "edges_from_both": edges_from_both,
            "id_collisions": id_collisions, "shadowed_files": shadowed_files,
            "cross_language_merges": cross_language_merges,
            "hotspot_threshold": hotspot_threshold, "hotspot_count": hotspot_count,
            "truncated": bool(files_truncated or imports_truncated or calls_truncated),
        }

        return {
            "project": display_name, "engine": "graph", "op": "c4",
            "fit": fit, "elements": elements, "relations": relations, "dropped": dropped,
            "stats": stats, "segment_titles": segment_titles, "reason": "",
        }
    except Exception as exc:
        log_swallowed("c4.build_c4_payload", exc)
        return {**_EMPTY, "reason": "error"}


