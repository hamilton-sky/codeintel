"""Build a LikeC4 architecture model (``.c4``) from the graph engine's Folder/File + IMPORTS +
CALLS|USAGE slice.

Same data->renderer->sink split as ``grapher.py``: ``build_c4_payload`` returns a plain
``{project, elements, relations, ...}`` dict; ``render_c4_dsl`` turns that payload into LikeC4 DSL
text; ``plan_output``/``write_model`` decide where that text is allowed to land on disk. All four
never raise.

Promoted from a prototype whose auto-fit depth and File->Symbol->file aggregation were validated
against 6 real repositories, with the 11 defects that review found fixed along the way (flat
``reason`` strings, out-of-scope edges counted not dropped, index-view cap, id collisions,
quote-escaping, no scope guessing, summed relation weights, capped dropped-edge report, O(1)
fan-in/out, degrade-only churn, no string-built Cypher).

**Edge source (measured, not assumed).** ``IMPORTS`` only sees MODULE-LEVEL imports — on this repo
that is a minority of the real cross-file structure, because the codebase is full of deliberately
lazy imports (``__main__``'s ``importlib``-driven command dispatch chief among them) — and it was
also found FABRICATING edges from source files to test files that do not reference them (a backend
bare-name-collision artifact, present in ``CALLS|USAGE`` too — see ``tests/test_c4.py``'s src->tests
pin). Measured live against this repo's own graph index at the auto-fit depth (58 elements):
``IMPORTS`` alone yields 60 element-pair relations; the UNION with ``CALLS|USAGE`` yields 193 — 59
of those confirmed by both sources, 1 by ``IMPORTS`` alone, and 133 found ONLY via ``CALLS|USAGE``,
including the known-true ``__main__ -> commands.*`` and ``gateway -> providers.*`` edges. The same
comparison on a second indexed repo (token-tracker) also showed ``CALLS|USAGE`` recovering
edges ``IMPORTS`` missed entirely. So this module aggregates the UNION of ``IMPORTS`` and
``CALLS|USAGE`` (already this codebase's higher-recall relation for fan-in — mapper.py's
``_FAN_IN_CYPHER`` — and for the call graph — grapher.py), keeping the existing noise/test/scope
filters (which already reject synthetic/non-source endpoints — nothing further needed there, unlike
``grapher.py``'s standalone ``_synth`` check, because every endpoint here is matched against the
``File`` nodes actually kept by ``keep_source`` rather than trusted verbatim). ``CALLS|USAGE`` is
still not complete: it did not recover most of ``__main__``'s ``importlib`` dispatch table either
(only 1 of its 15 dispatched command modules showed up), so the rendered model states its edge
source and does not claim full coverage of dynamic dispatch.
"""
