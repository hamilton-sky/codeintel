def _q(value: Any) -> str:
    """Escape a value for a single-quoted LikeC4 string literal (defect 6.5)."""
    return str(value).replace("\\", "\\\\").replace("'", "\\'")


def _tree(elements: list[dict]) -> dict:
    root: dict = {}
    for e in elements:
        node = root
        parts = e["id"].split(".")
        for i, part in enumerate(parts):
            node = node.setdefault(part, {"__children__": {}, "__leaf__": None})
            if i == len(parts) - 1:
                node["__leaf__"] = e
            node = node["__children__"]
    return root


def _emit_tree(node: dict, indent: int, out: list[str]) -> None:
    pad = "  " * indent
    for name, sub in sorted(node.items()):
        e, children = sub["__leaf__"], sub["__children__"]
        ident = _ident(name)
        if e is not None:
            kind = e["kind"]
            out.append(f"{pad}{ident} = {kind} '{_q(e['title'])}' {{")
            if e["fan_in"] >= 5:
                # Both, deliberately. The tag carries the exact risk colour and drives filtering,
                # but LikeC4 renders a tag as a ~2px corner stripe — measured, and next to invisible.
                # The viewer signals risk by colouring the WHOLE node, so a per-instance override
                # reproduces that behaviour. `red` is the nearest of the 11 legal element colours;
                # fidelity to the signal beats fidelity to the hex when the point is "impossible
                # to miss".
                out.append(f"{pad}  #hotspot")
                out.append(f"{pad}  style {{ color red }}")
            if e["tech"]:
                out.append(f"{pad}  technology '{_q(e['tech'])}'")
            meta = (f"path '{_q(e['path'])}'  files '{e['files']}'  churn '{e['churn']}'  "
                    f"fan_in '{e['fan_in']}'  fan_out '{e['fan_out']}'  "
                    f"internal_imports '{e['internal_imports']}'")
            out.append(f"{pad}  metadata {{ {meta} }}")
        else:
            # An intermediate path segment above the chosen depth with no element of its own —
            # a bare containment package so the containment tree survives (design section 3.3).
            out.append(f"{pad}{ident} = area '{_q(name)}' {{")
        if children:
            _emit_tree(children, indent + 1, out)
        out.append(f"{pad}}}")


def render_c4_dsl(payload: dict) -> str:
    """Render a `build_c4_payload` payload as LikeC4 DSL text. Never raises -- `""` on failure, so
    a downstream write never lands a half-written or leak-carrying model file."""
    try:
        # `elements` is NOT defaulted like the others: a malformed payload (e.g. `elements=None`,
        # a caller-side type error) must fail this function rather than silently render an empty
        # model — that distinction belongs to `build_c4_payload`'s `reason`, not to a renderer
        # guessing that "missing" and "empty" mean the same thing.
        elements = list(payload["elements"])
        relations = list(payload.get("relations") or [])
        dropped = list(payload.get("dropped") or [])
        stats = payload.get("stats") or {}
        fit = payload.get("fit") or {}
        project = payload.get("project") or "repo"

        table = fit.get("table") or {}
        table_str = " ".join(f"d{d}={table[d]}" for d in sorted(table))
        depth, how, cap = fit.get("depth"), fit.get("how"), fit.get("cap")
        over_cap = bool(fit.get("over_cap"))

        out: list[str] = []
        out.append("// Generated by codeintel from the graph index — do not edit by hand.")
        out.append(f"// project: {_q(project)}")
        # Edge-source disclosure is unconditional — it names what the model IS, not what this run
        # found, so it appears even when there are zero relations to report on.
        out.append("// edges: union of IMPORTS (static module-level imports) and CALLS|USAGE "
                   "(call/usage references) — CALLS|USAGE recovers most lazy, function-body and "
                   "conditional imports that IMPORTS alone misses")
        out.append("// coverage is NOT complete: dispatch through a name/lookup table (for "
                   "example an importlib-based command router) can still be invisible to both "
                   "relations, and CALLS|USAGE can attribute an edge to an unrelated same-named "
                   "symbol")
        out.append(f"// depth {depth} chosen ({how}): {table_str}"
                   + (f" — exceeds the {cap}-element view cap" if over_cap else ""))
        out.append(f"// {len(elements)} elements, {len(relations)} relations, "
                   f"{stats.get('files_kept', 0)} source files")
        if stats.get("edges_from_imports_only") or stats.get("edges_from_calls_usage_only"):
            out.append(f"// of those relations: {stats.get('edges_from_both', 0)} confirmed by "
                       f"BOTH sources, {stats.get('edges_from_imports_only', 0)} by IMPORTS only, "
                       f"{stats.get('edges_from_calls_usage_only', 0)} by CALLS|USAGE only "
                       f"(dashed `calls_usage` edges below)")
        if stats.get("edges_internal"):
            out.append(f"// {stats['edges_internal']} import/usage reference(s) folded into "
                       f"element cohesion (internal_imports) — not dropped")
        if stats.get("edges_dropped_out_of_scope"):
            out.append(f"// {stats['edges_dropped_out_of_scope']} import/usage reference(s) "
                       f"DROPPED: out-of-scope endpoint (excluded by noise/test/extension "
                       f"filters)")
        if stats.get("edges_dropped_ancestor"):
            out.append(f"// {stats['edges_dropped_ancestor']} import/usage reference(s) DROPPED: "
                       f"LikeC4 forbids an element relating to its own ancestor")
        if dropped:
            shown = dropped[:DROPPED_REPORT_CAP]
            out.extend(f"//   {d['from']} -> {d['to']}  ({d['why']})" for d in shown)
            total_dropped = (stats.get("edges_dropped_ancestor", 0)
                             + stats.get("edges_dropped_out_of_scope", 0))
            if total_dropped > len(shown):
                out.append(f"//   … and {total_dropped - len(shown)} more")
        if stats.get("id_collisions"):
            out.append(f"// {stats['id_collisions']} element id collision(s) resolved with a "
                       f"__2/__3 suffix")
        if stats.get("shadowed_files"):
            out.append(f"// {stats['shadowed_files']} file(s) shadow a sibling directory and "
                       f"were merged into it")
        if stats.get("truncated"):
            out.append("// NOTE: the file, import or call/usage scan hit its row cap — this "
                       "model may be INCOMPLETE")
        out.append("")
        out.append(SPECIFICATION_BLOCK)
        out.append("")
        out.append("model {")
        _emit_tree(_tree(elements), 1, out)
        if relations:
            out.append("")
            for r in sorted(relations, key=lambda x: (x["from"], x["to"])):
                kind = r.get("kind") or "imports"
                out.append(f"  {r['from']} -[{kind}]-> {r['to']} {{ metadata {{ n '{r['n']}' }} }}")
        out.append("}")
        out.append("")
        out.append("views {")
        if over_cap:
            out.append(f"  // view index SKIPPED: {len(elements)} elements exceeds the "
                       f"{cap}-element view cap — read --json for the full element list")
        else:
            roots = sorted({e["id"].split(".")[0] for e in elements})
            out.append("  view index {")
            out.append(f"    title '{_q(project)} — landscape'")
            # The provenance line the header already carries, repeated where a READER of the
            # rendered diagram will see it: LikeC4 shows `description` on the view's gallery card
            # and in the viewer chrome, while `//` header comments are visible only to whoever
            # opens the `.c4` source. Without it, a generated diagram is indistinguishable from a
            # hand-drawn one — and the edge caveats that make it honest live only in the comments.
            out.append(f"    description '{_q(VIEW_DESCRIPTION)}'")
            out.extend(f"    include {r}, {r}.**" for r in roots)
            out.append("    autoLayout TopBottom")
            out.append("  }")
        out.append("}")
        return "\n".join(out) + "\n"
    except Exception as exc:
        log_swallowed("c4.render_c4_dsl", exc)
        return ""


