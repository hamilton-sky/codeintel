def plan_output(out_dir: Any) -> dict:
    """Whether and how it is safe to write into *out_dir* — the fact-4 guarantee: LikeC4 merges
    every `.c4` in a directory into one project, so writing beside a foreign `.c4` file would
    produce duplicate-element parse errors. Never raises."""
    try:
        out_dir = str(out_dir or "")
        if os.path.isfile(out_dir):
            return {"ok": False, "action": "", "path": out_dir,
                    "problem": f"--out names a directory, not a file: {out_dir}"}
        if not os.path.isdir(out_dir):
            return {"ok": True, "action": "create", "path": out_dir, "problem": ""}

        c4_files = sorted(f for f in os.listdir(out_dir) if f.endswith(".c4"))
        marker_path = os.path.join(out_dir, MARKER_FILENAME)
        if os.path.isfile(marker_path):
            try:
                with open(marker_path, encoding="utf-8") as f:
                    marker = json.load(f)
            except Exception as exc:
                log_swallowed("c4.plan_output.marker", exc)
                marker = {}
            owned = set(marker.get("files") or [MODEL_FILENAME])
            if set(c4_files) <= owned:
                return {"ok": True, "action": "overwrite", "path": out_dir, "problem": ""}

        if c4_files:
            return {"ok": False, "action": "", "path": out_dir,
                    "problem": (f"{out_dir} already contains other .c4 files "
                                f"({', '.join(c4_files)}). LikeC4 merges every .c4 in a directory "
                                f"into ONE project, so writing here would produce duplicate-element "
                                f"errors. Use --out <empty-dir>.")}
        return {"ok": True, "action": "adopt", "path": out_dir, "problem": ""}
    except Exception as exc:
        log_swallowed("c4.plan_output", exc)
        return {"ok": False, "action": "", "path": str(out_dir), "problem": "error"}


def write_model(payload: dict, dsl: str, out_dir: Any) -> dict:
    """Write `model.c4` + the ownership marker into *out_dir*, refusing on an empty model or a
    `plan_output` refusal. Removes any file a PREVIOUS codeintel run produced that this run did
    not, so a stale artifact never lingers to merge into a later `likec4 build`. Never raises."""
    out_dir_str = str(out_dir or "")
    try:
        if not dsl:
            return {"ok": False, "path": out_dir_str, "files": [], "problem": "empty DSL — nothing to write"}
        if not (payload or {}).get("elements"):
            return {"ok": False, "path": out_dir_str, "files": [], "problem": "no elements — nothing to write"}

        plan = plan_output(out_dir)
        if not plan["ok"]:
            return {"ok": False, "path": plan["path"], "files": [], "problem": plan["problem"]}
        out_dir_str = plan["path"]

        os.makedirs(out_dir_str, exist_ok=True)
        marker_path = os.path.join(out_dir_str, MARKER_FILENAME)
        prev_files: set[str] = set()
        if os.path.isfile(marker_path):
            try:
                with open(marker_path, encoding="utf-8") as f:
                    prev_files = set((json.load(f)).get("files") or [])
            except Exception as exc:
                log_swallowed("c4.write_model.marker", exc)

        with open(os.path.join(out_dir_str, MODEL_FILENAME), "w", encoding="utf-8") as f:
            f.write(dsl)
        written = {MODEL_FILENAME}

        for stale in prev_files - written:
            stale_path = os.path.join(out_dir_str, stale)
            try:
                if os.path.isfile(stale_path):
                    os.remove(stale_path)
            except Exception as exc:
                log_swallowed("c4.write_model.stale", exc)

        fit = payload.get("fit") or {}
        marker = {
            "generator": "codeintel", "version": _generator_version(),
            "generated_at": datetime.now(UTC).isoformat(),
            "project": payload.get("project", ""), "depth": fit.get("depth"),
            "files": sorted(written), "elements": len(payload.get("elements") or []),
            "relations": len(payload.get("relations") or []),
        }
        with open(marker_path, "w", encoding="utf-8") as f:
            json.dump(marker, f, indent=2)

        return {"ok": True, "path": out_dir_str, "files": sorted(written), "problem": ""}
    except Exception as exc:
        log_swallowed("c4.write_model", exc)
        return {"ok": False, "path": out_dir_str, "files": [], "problem": "error"}


def _generator_version() -> str:
    try:
        from codeintel import __version__
        return __version__
    except Exception:
        return "0"
