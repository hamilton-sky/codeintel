"""The targets. Short, common names on purpose — that is the population where the damage is."""


def _broadcast(msg):
    """Reached directly, through a re-export chain, and shadowed by unrelated bindings."""
    return msg


def describe(name, fn):
    """Named after the worst failure observed in this project: a framework global in TypeScript."""
    return fn()


def filter(fn, items):
    """Shares its name with a builtin, so a bare `filter(...)` elsewhere is provably not this."""
    return [i for i in items if fn(i)]
